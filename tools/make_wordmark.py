"""Generate matching outlined website logos and a compact firmware wordmark.
Requires fontTools and Pillow. Font files are not distributed; only this wordmark.
"""
from pathlib import Path
import argparse, math, xml.etree.ElementTree as ET
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.boundsPen import BoundsPen
from PIL import Image, ImageDraw, ImageFont
ROOT=Path(__file__).resolve().parents[1]
p=argparse.ArgumentParser();p.add_argument('--font',default='C:/Windows/Fonts/seguibli.ttf');a=p.parse_args()
color=(ROOT/'web/gamedude-color-logo.svg').exists()
font=TTFont(a.font);glyphs=font.getGlyphSet();cmap=font.getBestCmap();units=font['head'].unitsPerEm
ink='#eee9f7';rainbow=['#ff798b','#b48dff','#bdf69c','#ffe25a','#29e6ff']
letters='GAMEDUDE'+(' COLOR' if color else '')
positions=[];cursor=0;bounds=[]
for i,ch in enumerate(letters):
    glyph=glyphs[cmap[ord(ch)]]
    if ch!=' ':
        pen=BoundsPen(glyphs);glyph.draw(pen);x0,y0,x1,y1=pen.bounds
        bounds.append((cursor+x0,y0,cursor+x1,y1))
        positions.append((ch,cursor,1 if i<8 else i-7))
    cursor+=glyph.width-35
left=min(b[0] for b in bounds);bottom=min(b[1] for b in bounds);right=max(b[2] for b in bounds);top=max(b[3] for b in bounds)
scale=42/(top-bottom);width=math.ceil((right-left)*scale+8);height=50
NS='http://www.w3.org/2000/svg';ET.register_namespace('',NS)
def svg(dark=False):
    root=ET.Element('{'+NS+'}svg',viewBox=f'0 0 {width} {height}',width=str(width),height=str(height),role='img',attrib={'aria-label':'GameDude'+(' Color' if color else '')})
    ET.SubElement(root,'title').text='GameDude'+(' Color' if color else '')
    for ch,x,index in positions:
        pen=SVGPathPen(glyphs);glyphs[cmap[ord(ch)]].draw(pen)
        fill=('#29344b' if dark else ink) if index==1 else rainbow[index-2]
        ET.SubElement(root,'path',d=pen.getCommands(),fill=fill,transform=f'matrix({scale:.8f} 0 0 {-scale:.8f} {4+(x-left)*scale:.6f} {4+top*scale:.6f})')
    return ET.tostring(root,encoding='unicode')+'\n'
name='gamedude-color-logo' if color else 'gamedude-logo'
(ROOT/'web'/f'{name}.svg').write_text(svg(),encoding='utf-8')
(ROOT/'web'/f'{name}-dark.svg').write_text(svg(True),encoding='utf-8')
# Render the same positioned glyphs, then pack two indexed pixels per byte.
w=224;h=round(w*height/width);super_scale=4
image=Image.new('L',(w,h))
raster_scale=(w*super_scale)/(width/scale)
face=ImageFont.truetype(a.font,max(1,round(units*raster_scale)))
for ch,x,index in positions:
    mask=Image.new('L',(w*super_scale,h*super_scale));draw=ImageDraw.Draw(mask)
    draw.text(((4/scale+x-left)*raster_scale,(4/scale+top)*raster_scale),ch,font=face,fill=255,anchor='ls',stroke_width=0)
    mask=mask.resize((w,h),Image.Resampling.LANCZOS).point(lambda v:255 if v>=112 else 0)
    image.paste(index,(0,0),mask)
raw=list(image.getdata());packed=[raw[i]|((raw[i+1] if i+1<len(raw) else 0)<<4) for i in range(0,len(raw),2)]
def rgb565(v):
    r,g,b=bytes.fromhex(v[1:]);return (r>>3)<<11|(g>>2)<<5|(b>>3)
palette=[0,rgb565(ink)]+[rgb565(c) for c in rainbow]
text='/* Generated by tools/make_wordmark.py. Static wordmark; no font embedded. */\n#pragma once\n'
text+=f'#define GD_MARK_WIDTH {w}u\n#define GD_MARK_HEIGHT {h}u\n'
text+='static const uint16_t gd_mark_palette[]={'+','.join(hex(v) for v in palette)+'};\n'
text+='static const uint8_t gd_mark_pixels[]={\n'+''.join(','.join(str(b) for b in packed[i:i+32])+',\n' for i in range(0,len(packed),32))+'};\n'
text+='static inline unsigned gd_mark_index(unsigned x,unsigned y){unsigned i=y*GD_MARK_WIDTH+x;return (gd_mark_pixels[i/2]>>((i&1)*4))&15;}\n'
(ROOT/'firmware/wordmark.h').write_text(text)
preview=Image.new('RGB',(240,64),'#101828');px=preview.load()
colors=[(0,0,0)]+[tuple(bytes.fromhex(c[1:])) for c in [ink,*rainbow]]
for y in range(h):
    for x in range(w):
        if raw[y*w+x]:px[x+8,y+12]=colors[raw[y*w+x]]
(ROOT/'build').mkdir(exist_ok=True);preview.save(ROOT/'build/wordmark-preview.png')
print(f'{name}: {width}x{height} SVG; {w}x{h} firmware, {len(packed)} bytes')
